using AppDtos.Pets;
using AppDtos.Pets.Requests;
using Petstore.Api.Tests.Services.Pets;
using Petstore.Api.Tests.Tests.Contexts;
using Reqnroll;
using System.Net;

namespace Petstore.Api.Tests.Tests.StepDefinitions.CreatePet;

[Binding]
public class CreatePetThenSteps(PetContext context, ApiResponseMetadataContext responseMetadata, PetsService pets)
{
    [Then("the create response contains the submitted pet data")]
    public void ThenTheCreateResponseContainsTheSubmittedPetData()
    {
        Assert.AreEqual(HttpStatusCode.OK, responseMetadata.StatusCode);
        Assert.IsNotNull(context.CreatePetResponse, "The response must contain a pet");

        AssertPetsAreEqual(context.CreatePetRequest, context.CreatePetResponse);
    }

    [Then("the create response contains the submitted pet data with random ID")]
    public void ThenTheCreateResponseContainsTheSubmittedPetDataWithRendomId()
    {
        Assert.AreEqual(HttpStatusCode.OK, responseMetadata.StatusCode);
        Assert.IsNotNull(context.CreatePetResponse, "The response must contain a pet");

        var expected = context.CreatePetRequest;
        expected.Id = null; // The ID is generated by the server, so we ignore it in the comparison
        AssertPetsAreEqual(expected, context.CreatePetResponse);
    }

    [Then("the pet can be retrieved with the submitted data")]
    public async Task ThenThePetCanBeRetrievedWithTheSubmittedData()
    {
        var id = context.CreatePetResponse!.Id!.Value;
        var retrieved = await pets.GetPetAsync(id.ToString());

        Assert.AreEqual(HttpStatusCode.OK, retrieved.StatusCode);
        Assert.IsNotNull(retrieved.Body, "The created pet could not be retrieved");
        Assert.AreEqual(id, retrieved.Body.Id, "Unexpected pet ID");

        AssertPetsAreEqual(context.CreatePetRequest, retrieved.Body);
    }

    [Then("the pet can NOT be retrieved by ID {string}")]
    public async Task ThenThePetCannotBeRetrievedByInvalidId(string id)
    {
        var result = await pets.GetPetWithErrorAsync(id);

        Assert.AreEqual("error", result.Body!.Type, "Expected an error response");
        Assert.AreEqual("Pet not found", result.Body!.Message, "Unexpected error message");

        responseMetadata.StatusCode = result.StatusCode;
    }

    private static void AssertPetsAreEqual(IPetDto submitted, IPetDto actual)
    {
        if (submitted.Id is null)
        {
            Assert.IsNotNull(actual.Id, "Expected a generated ID");
        }
        else {
            Assert.AreEqual(submitted.Id, actual.Id, "ID should be equal");
        }

        Assert.AreEqual(submitted.Name, actual.Name, "Unexpected pet name");
        CollectionAssert.AreEqual(submitted.PhotoUrls, actual.PhotoUrls, "Unexpected photo URLs");
        Assert.AreEqual(submitted.Status, actual.Status, "Unexpected pet status");

        if (submitted.Category is not null && submitted.Category!.Id is null)
        {
            Assert.AreEqual(submitted.Category.Name, actual.Category!.Name, "Unexpected category name");
        }
        else {
            Assert.AreEquivalent<CategoryDto>(submitted.Category, actual.Category, strict: true, message: "Unexpected category");
        }


        if (submitted.Tags is null)
        {
            Assert.IsEmpty(actual.Tags!, "Expected empty tags list");
        }
        else {
            Assert.AreEquivalent<List<TagDto>>(submitted.Tags, actual.Tags, strict: true, message: "Unexpected tags");
        }
    }
}
